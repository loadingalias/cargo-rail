#[test]
fn test_init_detects_policy_from_cargo_toml() -> Result<()> {
  let ws = TestWorkspace::new_named("init-policy")?;
  ws.remove_config()?; // Remove default config for init test

  // Update workspace Cargo.toml to add rust-version to existing workspace.package
  let cargo_toml = &ws.path.join("Cargo.toml");
  let existing_content = std::fs::read_to_string(cargo_toml)?;

  // Add rust-version to existing [workspace.package] section
  let new_content = existing_content.replace("edition = \"2021\"", "edition = \"2021\"\nrust-version = \"1.75.0\"");
  std::fs::write(cargo_toml, new_content)?;

  // Run init
  run_cargo_rail(&ws.path, &["rail", "init", "--non-interactive"])?;

  // Verify config detects policy
  let config_content = std::fs::read_to_string(ws.path.join(".config/rail.toml"))?;
  assert!(
    config_content.contains("resolver = \"2\""),
    "should detect resolver from Cargo.toml"
  );
  assert!(
    config_content.contains("edition = \"2021\""),
    "should detect edition from Cargo.toml"
  );
  assert!(
    config_content.contains("msrv = \"1.75.0\""),
    "should detect MSRV from rust-version"
  );

  Ok(())
}

#[test]
fn test_init_dry_run() -> Result<()> {
  let ws = TestWorkspace::new_named("init-dry-run")?;
  ws.remove_config()?; // Remove default config for init test

  // Run init with --dry-run
  let output = run_cargo_rail(&ws.path, &["rail", "init", "--dry-run", "--non-interactive"])?;

  // Verify success
  assert!(output.status.success(), "dry-run should succeed");

  // Verify config was NOT created
  let config_path = &ws.path.join(".config/rail.toml");
  assert!(!config_path.exists(), "config file should NOT be created in dry-run");

  // Verify output shows config
  let stdout = String::from_utf8_lossy(&output.stdout);
  assert!(stdout.contains("--- .config/rail.toml ---"));
  assert!(stdout.contains("[workspace]"));
  assert!(stdout.contains("[toolchain]"));

  Ok(())
}

