#[test]
fn test_init_all_fields_present() -> Result<()> {
  let ws = TestWorkspace::new_named("init-all-fields")?;
  ws.remove_config()?; // Remove default config for init test

  // Run init
  run_cargo_rail(&ws.path, &["rail", "init", "--non-interactive"])?;

  let config_content = std::fs::read_to_string(ws.path.join(".config/rail.toml"))?;

  // Verify ALL config sections and fields are present (active or commented)

  // Workspace
  assert!(config_content.contains("root = \".\""));

  // Toolchain
  assert!(config_content.contains("channel = "));
  assert!(config_content.contains("profile = "));
  assert!(config_content.contains("components = "));
  assert!(config_content.contains("targets = "));

  // Unify
  assert!(config_content.contains("use_all_features = "));
  assert!(config_content.contains("validate_targets = "));
  assert!(config_content.contains("max_parallel_jobs = "));
  assert!(config_content.contains("pin_transitives = "));
  assert!(config_content.contains("pin_hosts = "));

  // Policy - all fields should be present (active or commented)
  assert!(
    config_content.contains("resolver = ") || config_content.contains("# resolver = "),
    "resolver field should be present"
  );
  assert!(
    config_content.contains("msrv = ") || config_content.contains("# msrv = "),
    "msrv field should be present"
  );
  assert!(
    config_content.contains("edition = ") || config_content.contains("# edition = "),
    "edition field should be present"
  );
  assert!(
    config_content.contains("forbid_multiple_versions = "),
    "forbid_multiple_versions should be present"
  );
  assert!(
    config_content.contains("require_workspace_inheritance = "),
    "require_workspace_inheritance should be present"
  );
  assert!(
    config_content.contains("# allowed_licenses = "),
    "allowed_licenses should be commented"
  );
  assert!(
    config_content.contains("# forbid_patch_replace = "),
    "forbid_patch_replace should be commented"
  );

  // Security - all fields should be present (active or commented)
  assert!(
    config_content.contains("# ssh_key_path = "),
    "ssh_key_path should be commented"
  );
  assert!(
    config_content.contains("# signing_key_path = "),
    "signing_key_path should be commented"
  );
  assert!(
    config_content.contains("require_signed_commits = "),
    "require_signed_commits should be present"
  );
  assert!(
    config_content.contains("# pr_branch_pattern = "),
    "pr_branch_pattern should be commented"
  );
  assert!(
    config_content.contains("protected_branches = "),
    "protected_branches should be present"
  );

  // Split/Sync - example should be present
  assert!(config_content.contains("# [[splits]]"));
  assert!(config_content.contains("# name = "));
  assert!(config_content.contains("# remote = "));
  assert!(config_content.contains("# branch = "));
  assert!(config_content.contains("# mode = "));

  Ok(())
}
